<?php
/**
 * Server-side markup for the Career CTA block.
 *
 * @package SparkAgency
 */

defined( 'ABSPATH' ) || exit;

$brand = isset( $attributes['brand'] ) && in_array( $attributes['brand'], array( 'agency', 'works', 'exp', 'warsaw', 'health', 'studio' ), true ) ? $attributes['brand'] : 'agency';
$theme = isset( $attributes['theme'] ) && 'light' === $attributes['theme'] ? 'light' : 'dark';

$eyebrow         = isset( $attributes['eyebrow'] ) ? $attributes['eyebrow'] : '';
$title           = isset( $attributes['title'] ) ? $attributes['title'] : '';
$description     = isset( $attributes['description'] ) ? $attributes['description'] : '';
$primary_label   = isset( $attributes['primaryLabel'] ) ? $attributes['primaryLabel'] : '';
$primary_url     = isset( $attributes['primaryUrl'] ) ? $attributes['primaryUrl'] : '';
$secondary_label = isset( $attributes['secondaryLabel'] ) ? $attributes['secondaryLabel'] : '';
$secondary_url   = isset( $attributes['secondaryUrl'] ) ? $attributes['secondaryUrl'] : '';

$show_primary   = ! isset( $attributes['showPrimaryButton'] ) || (bool) $attributes['showPrimaryButton'];
$show_secondary = ! isset( $attributes['showSecondaryButton'] ) || (bool) $attributes['showSecondaryButton'];

$wrapper_attributes = get_block_wrapper_attributes(
	array(
		'class'        => 'spark-career-cta',
		'data-brand'   => $brand,
		'data-theme'   => $theme,
		'aria-label'   => $title ? wp_strip_all_tags( $title ) : __( 'Kariera', 'sparkagency' ),
	)
);
?>
<section <?php echo $wrapper_attributes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress core. ?> >
	<div class="spark-career-cta__wrap">
		<div class="spark-career-cta__band">
			<div class="spark-career-cta__copy">
				<?php if ( $eyebrow ) : ?>
					<span class="spark-career-cta__eyebrow"><?php echo esc_html( $eyebrow ); ?></span>
				<?php endif; ?>
				<?php if ( $title ) : ?>
					<h2><?php echo wp_kses_post( $title ); ?></h2>
				<?php endif; ?>
				<?php if ( $description ) : ?>
					<div class="spark-career-cta__description"><?php echo wp_kses_post( $description ); ?></div>
				<?php endif; ?>
			</div>
			<?php if ( ( $show_primary && $primary_label ) || ( $show_secondary && $secondary_label ) ) : ?>
				<div class="spark-career-cta__actions">
					<?php if ( $show_primary && $primary_label ) : ?>
						<a class="spark-career-cta__button spark-career-cta__button--primary" href="<?php echo esc_url( $primary_url ); ?>"><?php echo esc_html( $primary_label ); ?></a>
					<?php endif; ?>
					<?php if ( $show_secondary && $secondary_label ) : ?>
						<a class="spark-career-cta__button spark-career-cta__button--secondary" href="<?php echo esc_url( $secondary_url ); ?>"><?php echo esc_html( $secondary_label ); ?></a>
					<?php endif; ?>
				</div>
			<?php endif; ?>
		</div>
	</div>
</section>
